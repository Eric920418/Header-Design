const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { chromium } = require('playwright')

// 使用現有 Playwright；PREVIEW_PASSWORD 由環境提供，不在檢查檔內儲存密碼。
async function main() {
  assert(process.env.PREVIEW_PASSWORD, '請設定 PREVIEW_PASSWORD')
  const base = process.env.PREVIEW_URL || 'http://127.0.0.1:3018'
  const output = fs.mkdtempSync(path.join(os.tmpdir(), 'sakura-ppt-check-'))
  console.log(`截圖：${output}`)
  const browser = await chromium.launch({ headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const login = await context.request.post(`${base}/api/preview-access`, { data: { password: process.env.PREVIEW_PASSWORD } })
    assert.equal(login.status(), 200, '預覽登入失敗')
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    const go = async url => {
      console.log(`檢查 ${url}`)
      const response = await page.goto(base + url)
      assert.equal(response.status(), 200, url)
      await page.evaluate(() => document.fonts.ready)
      await page.waitForTimeout(1000)
    }
    const screenshot = async (selector, name) => {
      const element = page.locator(selector).first()
      await element.scrollIntoViewIfNeeded()
      await page.waitForTimeout(900)
      await element.screenshot({ path: path.join(output, `${name}.png`) })
    }
    if (process.env.CHECK_FOOTER_ONLY !== '1') {
    await go('/')
    assert(await page.locator('a[href="/design-inspiration?style=%E8%BC%95%E5%A5%A2%E9%A2%A8"]').count(), '首頁輕奢分類連結')
    assert(await page.locator('a.group\\/svc[href="/products/sakura"]').count(), '首頁廚電入口')
    await page.getByRole('button', { name: '廚房產品', exact: true }).hover()
    await page.waitForTimeout(350)
    await screenshot('.desktop-nav-item:has(> button[aria-expanded="true"]) > div', '01-product-menu')
    await page.mouse.wheel(0, 300)
    await page.waitForTimeout(400)
    assert.equal(await page.getByRole('button', { name: '廚房產品', exact: true }).getAttribute('aria-expanded'), 'false')
    await go('/')
    await page.locator('#contact').scrollIntoViewIfNeeded()
    await page.waitForTimeout(900)
    await page.getByLabel('選擇區域').selectOption('中部')
    await page.getByLabel('選擇城市').selectOption('臺中市')
    for (const name of ['中港店', '松竹店', '台中復興店', '博館店']) assert(await page.getByText(name, { exact: true }).count(), name)
    await screenshot('#contact', '07-stores')
    } else {
      await go('/')
    }
    await screenshot('footer', '09-footer')
    const alignment = await page.evaluate(() => {
      const x = selector => document.querySelector(selector).getBoundingClientRect().left
      return [x('.footer-social-links a:first-child') - x('[data-footer-align-anchor="builders"]'), x('.footer-social-links a:last-child') - x('[data-footer-align-anchor="sakura-group"]')]
    })
    assert(alignment.every(delta => Math.abs(delta) < 2), `頁尾對齊 ${alignment}`)
    assert.equal(await page.locator('footer a[href="/privacy"]').getAttribute('target'), '_blank')
    const retiredSitemap = await context.request.get(base + '/sitemap', { maxRedirects: 0 })
    assert.equal(retiredSitemap.status(), 301)
    assert.equal(retiredSitemap.headers().location, '/#footer-navigation')
    assert.equal(await page.locator('a[href="/sitemap"]').count(), 0)
    const sitemapToggle = page.getByRole('button', { name: '網站地圖', exact: true })
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: 1000 })
      assert.equal(await sitemapToggle.getAttribute('aria-expanded'), 'false')
      assert.equal(await page.locator('#footer-sitemap').isVisible(), false)
      await sitemapToggle.focus()
      await page.keyboard.press('Enter')
      assert.equal(await sitemapToggle.getAttribute('aria-expanded'), 'true')
      assert.equal(await page.locator('#footer-sitemap').isVisible(), true)
      assert.equal(await page.locator('#footer-sitemap h2').count(), 6)
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px Footer 溢出`)
      assert(await page.locator('#footer-sitemap a').evaluateAll(links => links.every(link => link.getBoundingClientRect().right <= innerWidth - 75)), `${width}px 頁尾連結被右側浮動按鈕遮住`)
      await screenshot('footer', `footer-sitemap-${width}`)
      await sitemapToggle.focus()
      await page.keyboard.press('Space')
      assert.equal(await page.locator('#footer-sitemap').isVisible(), false)
    }
    await sitemapToggle.click()
    for (const href of await page.locator('#footer-sitemap a').evaluateAll(items => items.map(item => item.getAttribute('href')))) {
      assert.equal((await context.request.get(base + href)).status(), 200, `網站地圖 ${href}`)
    }
    await sitemapToggle.click()
    await page.setViewportSize({ width: 1440, height: 1000 })
    await go('/sitemap')
    assert.equal(new URL(page.url()).pathname, '/')
    assert.equal(new URL(page.url()).hash, '#footer-navigation')
    assert.equal(await page.getByRole('heading', { name: 'Site Map', exact: true }).count(), 0)
    if (process.env.CHECK_FOOTER_ONLY === '1') {
      assert.deepEqual(errors, [], 'Footer 前端執行錯誤')
      console.log('Footer：三種寬度、鍵盤展開收合、全部分類連結及舊網址重新導向通過')
      return
    }
    await go('/design-inspiration?style=輕奢風')
    assert.equal(await page.locator('#design-style').inputValue(), '輕奢風')
    const options = await page.locator('#design-style option').allTextContents()
    assert(options.includes('美式風') && !options.includes('日式簡約風'))
    assert(await page.locator('#design-form option[value="ㄇ型+中島"]').count())
    await go('/home-style/aikitchen')
    assert.equal(await page.locator('.ai-intro__content h3').evaluate(e => getComputedStyle(e).fontSize), '30px')
    assert.equal(await page.locator('.ai-intro__paragraphs').evaluate(e => getComputedStyle(e).rowGap), '8px')
    assert.equal(await page.locator('a[href="/catalogues/kitchenware-catalog?series=aikitchen"]').getAttribute('target'), '_blank')
    await go('/catalogues/kitchenware-catalog?series=aikitchen')
    assert.equal(await page.locator('h1').innerText(), 'Series Catalogue')
    assert.match(await page.locator('.catalogue-hero__trail').innerText(), /AI廚房/)
    await go('/catalogues/kitchenware-catalog?series=unknown')
    assert.doesNotMatch(await page.locator('.catalogue-hero__trail').innerText(), /unknown|AI廚房/)
    for (const url of ['/products/sakura/range-hood', '/products/sakura/range-hood/near-suction', '/products/sakura/range-hood/near-suction/r7600']) {
      await go(url)
      const title = page.locator('h2').filter({ hasText: /Kitchen.*Product.*Catalogue/s })
      assert.equal(await title.locator('em').evaluate(e => getComputedStyle(e).color), 'rgb(202, 160, 92)')
      assert.match(await title.locator('span').evaluate(e => getComputedStyle(e).fontFamily), /Cal Sans/)
      assert.equal(await page.locator('section[class$="catalogue"] h3').first().evaluate(e => getComputedStyle(e).fontWeight), '600')
    }
    await go('/products/sakura/range-hood/near-suction/r7600')
    assert.match(await page.locator('.product-detail-hero__trail').innerText(), /SAKURA 廚電/)
    const track = page.locator('.related-products__grid')
    await track.scrollIntoViewIfNeeded()
    const previous = await track.evaluate(e => getComputedStyle(e).transform)
    await page.getByRole('button', { name: '下一組相關產品' }).click()
    await page.waitForTimeout(180)
    assert.notEqual(await track.evaluate(e => getComputedStyle(e).transform), previous, '相關產品沒有滑動')
    await page.setViewportSize({ width: 1440, height: 600 })
    await page.getByRole('button', { name: '詳細規格', exact: true }).click()
    const panel = page.locator('.product-specifications-dialog__panel')
    assert(await panel.evaluate(e => e.scrollHeight > e.clientHeight), '測試視窗未產生規格溢出')
    await panel.hover()
    await page.mouse.wheel(0, 600)
    await page.waitForTimeout(400)
    assert(await panel.evaluate(e => e.scrollTop > 0), '規格視窗滾輪無效')
    await screenshot('dialog[open]', '20-specifications')
    await page.keyboard.press('Escape')
    await page.setViewportSize({ width: 1440, height: 1000 })
    await go('/catalogues/catalog')
    assert.equal(await page.locator('h1').innerText(), 'Kitchen Catalogue')
    await page.locator('.product-catalogue-projects').scrollIntoViewIfNeeded()
    await page.waitForTimeout(900)
    await page.locator('.product-catalogue-card__link').first().hover()
    await page.waitForTimeout(550)
    assert.equal(await page.locator('.product-catalogue-card__action > span:first-child').first().innerText(), '預覽')
    assert.equal(await page.locator('.product-catalogue-card__download').count(), 5)
    assert.equal(await page.locator('.product-catalogue-card__text strong').first().evaluate(e => getComputedStyle(e).fontSize), '20px')
    assert.equal((await context.request.get(`${base}/api/catalogues/not-a-catalogue`)).status(), 404)
    for (const href of await page.locator('.product-catalogue-card__download').evaluateAll(items => items.map(item => item.getAttribute('href')))) {
      const download = await context.request.get(base + href, { timeout: 40000 })
      assert.equal(download.status(), 200, href)
      assert.match(download.headers()['content-disposition'], /^attachment;/)
      assert.equal((await download.body()).subarray(0, 5).toString(), '%PDF-')
    }
    const centre = await page.locator('.product-care__media-arrow').evaluate(e => {
      const a = e.getBoundingClientRect(), b = e.parentElement.getBoundingClientRect()
      return [a.x + a.width / 2 - b.x - b.width / 2, a.y + a.height / 2 - b.y - b.height / 2]
    })
    assert(centre.every(n => Math.abs(n) < 2), `保養按鈕未置中 ${centre}`)
    await screenshot('.product-care', '24-product-care')
    await go('/service-process')
    await screenshot('.antra-service-video', '25-coming-soon')
    assert(await page.getByText('Coming Soon', { exact: true }).isVisible())
    assert.equal(await page.locator('.antra-service-video button').isDisabled(), true)
    await go('/gallery/case35')
    assert.equal(await page.locator('.case-detail-booking').getAttribute('href'), 'https://pse.is/9kq37z')
    assert.match(await page.locator('.case-detail-carousel img').first().getAttribute('src'), /asset_11_2026/)
    await screenshot('.case-detail-carousel', '28-case35')
    assert.match(await page.locator('.case-detail-story img').last().getAttribute('src'), /asset_03_2026/)
    await go('/knowledge')
    const guideHero = await page.locator('.hero-includes-header').evaluate(e => e.offsetHeight)
    await go('/knowledge/design/systemcabinet')
    assert(Math.abs(await page.locator('.hero-includes-header').evaluate(e => e.offsetHeight) - guideHero) < 2, '指南文章 Hero 高度')
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: 1000 })
      await go('/franchising/download')
      const reference = await page.locator('.hero-includes-header').evaluate(e => e.getBoundingClientRect().height)
      await go('/privacy')
      assert.equal(await page.locator('h1').evaluate(e => getComputedStyle(e).fontSize), '38px')
      const privacyHeight = await page.locator('.hero-includes-header').evaluate(e => e.getBoundingClientRect().height)
      assert(Math.abs(reference - privacyHeight) < 2, `隱私 Hero ${width}: ${privacyHeight}/${reference}`)
      for (const url of ['/catalogues/catalog', '/gallery', '/service-process', '/knowledge/design/systemcabinet']) {
        await go(url)
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width} ${url} 橫向溢出`)
        if (url === '/gallery') assert.equal(await page.locator('.antra-store-filter button').first().evaluate(e => getComputedStyle(e).fontSize), '16px')
      }
      if (width === 390) await screenshot('.hero-includes-header', '15-mobile-article-hero')
    }
    assert.deepEqual(errors, [], '前端執行錯誤')
    console.log(`PPT 修改驗證通過；截圖：${output}`)
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
