const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { chromium } = require('playwright')

async function main() {
  assert(process.env.PREVIEW_PASSWORD, '請設定 PREVIEW_PASSWORD')
  const base = process.env.PREVIEW_URL || 'http://127.0.0.1:3018'
  const output = fs.mkdtempSync(path.join(os.tmpdir(), 'sakura-partnership-check-'))
  console.log(output)
  const browser = await chromium.launch({ headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
    assert.equal((await context.request.post(base + '/api/preview-access', { data: { password: process.env.PREVIEW_PASSWORD } })).status(), 200)
    const page = await context.newPage()
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    const go = async url => {
      console.log(url)
      assert.equal((await page.goto(base + url)).status(), 200)
      await page.evaluate(() => document.fonts.ready)
      await page.waitForTimeout(1500)
    }
    const reveal = async selector => {
      const el = page.locator(selector).first()
      await el.scrollIntoViewIfNeeded()
      await page.waitForTimeout(1800)
      return el
    }
    const shot = async (selector, name) => (await reveal(selector)).screenshot({ path: path.join(output, name + '.png') })
    const css = (selector, key) => page.locator(selector).first().evaluate((e, k) => getComputedStyle(e)[k], key)
    const rect = selector => page.locator(selector).first().boundingBox()
    const center = r => r.x + r.width / 2
    await go('/news/latest/kaohsiung_opening')
    assert.equal(await css('.latest-detail-cover img', 'objectFit'), 'cover')
    await shot('.latest-detail-cover', '01-news')
    await go('/about/advantage')
    const pavilion = await rect('.brand-h8-nav a[href="/about/exhibition"] span'), arrow = await rect('.brand-h8-scroll')
    assert(Math.abs(center(pavilion) - center(arrow)) < 2, '箭頭必須對齊集團品牌館文字，而非整排導覽中心')
    for (const width of [1920, 1366, 1024, 768, 390]) {
      await page.setViewportSize({ width, height: 1000 })
      await page.waitForTimeout(200)
      assert(Math.abs(center(await rect('.brand-h8-nav a[href="/about/exhibition"] span')) - center(await rect('.brand-h8-scroll'))) < 2, `${width}px 集團品牌館箭頭偏移`)
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    assert.equal(await css('.brand-h8-intro', 'paddingTop'), '104px')
    await shot('.brand-h8-intro', '02-brand-hero')
    await go('/about/introduce')
    await shot('.about-services__panel', '03-history')
    const alignment = await page.locator('.about-services__item').first().evaluate(e => {
      const year = e.querySelector('.about-services__year'), answer = e.querySelector('.about-services__answer p')
      return answer.getBoundingClientRect().left + parseFloat(getComputedStyle(answer).paddingLeft) - year.getBoundingClientRect().right - parseFloat(getComputedStyle(year).marginRight)
    })
    assert(Math.abs(alignment) < 1, '歷史答案沒有對齊題目')
    await reveal('.about-identity__carousel')
    assert.equal(await css('#about-identity-title', 'fontSize'), '60px')
    await page.getByRole('button', { name: '下一張品牌辨識', exact: true }).click()
    await page.waitForTimeout(700)
    assert(await page.locator('.about-identity__grid').evaluate(e => e.scrollLeft > 0), '品牌辨識箭頭未移動')
    await shot('.about-identity__carousel', '04-identity')
    await go('/')
    await reveal('.home-project-carousel')
    const before = await css('.home-project-track', 'transform')
    await page.getByRole('button', { name: '下一個廚房系列', exact: true }).click()
    await page.waitForTimeout(300)
    assert.notEqual(await css('.home-project-track', 'transform'), before, '首頁系列箭頭未移動')
    await go('/franchising/intro')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    for (const width of [1920, 1440, 1280, 1025]) {
      await page.setViewportSize({ width, height: 1000 })
      assert(await page.locator('.franchise-post-grid').evaluateAll(groups => groups.length === 3 && groups.every(group => {
        const cards = [...group.querySelectorAll('.franchise-post')]
        return ['.franchise-post__content', '.franchise-post__content p', '.franchise-post__features'].every(selector => {
          const [left, right] = cards.map(card => card.querySelector(selector).getBoundingClientRect())
          return Math.abs(left.top - right.top) < 1 && Math.abs(left.height - right.height) < 1
        })
      })), `${width}px 加盟優勢內文與圖示列必須等高對齊`)
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await shot('.franchise-advantages__layout', '05-advantages')
    assert.equal(await page.locator('#franchise-advantage-title span').textContent(), 'Success Starts')
    assert.equal(await css('#franchise-advantage-title span', 'color'), 'rgb(202, 160, 92)')
    assert.equal((await css('.franchise-post__features', 'gridTemplateColumns')).split(' ').length, 3)
    await shot('.source-split-heading', '06-celebrity')
    assert.match(await page.locator('#franchise-marketing-title').textContent(), /Celebrity Stories That InspireBeautiful Living/)
    await reveal('.franchise-support-panel')
    await shot('.franchise-process__details', '07-support')
    assert.equal(await css('.franchise-process__details', 'borderTopLeftRadius'), '24px')
    assert.equal(await page.locator('.franchise-support-panel__cta .site-cta-icon').count(), 1)
    await shot('.franchise-faq__promo', '08-faq')
    assert(Math.abs(center(await rect('.franchise-faq__promo-image')) - center(await rect('.franchise-faq__promo-arrow'))) < 1)
    await go('/franchising/form')
    assert.equal(await css('#franchise-application-title', 'fontSize'), '38px')
    assert.equal(await page.getByText('線上送出服務正在串接中', { exact: true }).count(), 0)
    // Never send test identity data to a configured external endpoint.
    await page.route('**/*', route => route.request().method() === 'POST' ? route.abort() : route.continue())
    await reveal('.application-form__submit-row')
    await page.getByRole('button', { name: '確認送出', exact: true }).click()
    assert.match(await page.locator('.application-form__notice').textContent(), /申請資料尚未完成/)
    for (const [name, value] of Object.entries({ name: '測試使用者', email: 'preview@example.com', phone: '0900000000', area: '台中' })) {
      await page.locator(`input[name="${name}"]`).fill(value)
    }
    await page.locator('input[name="experience"][value="否"]').check()
    await page.locator('select[name="budget"]').selectOption('200萬以下')
    await page.locator('select[name="timeline"]').selectOption('暫無計畫')
    await page.locator('input[name="consent"]').check()
    await page.getByRole('button', { name: '確認送出', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('.application-form__notice')?.textContent.includes('ConfigurationError'))
    assert.match(await page.locator('.application-form__notice').textContent(), /申請資料未送出/)
    await page.unroute('**/*')
    await go('/franchising/download')
    assert.equal(await css('#franchise-download-title', 'fontSize'), '64px')
    assert.equal(await css('#franchise-document-title', 'fontSize'), '38px')
    assert.equal(await css('#franchise-document-title span', 'color'), 'rgb(202, 160, 92)')
    await shot('.download-document__header', '10-download')
    await go('/builders')
    await shot('.builders-team__grid', '11-brands')
    assert.equal(await page.locator('.builders-team-card--coming-soon').count(), 3)
    const logoBefore = await rect('.builders-team-card__logo')
    await page.locator('.builders-team-card--project').hover()
    await page.waitForTimeout(500)
    assert.deepEqual(await rect('.builders-team-card__logo'), logoBefore, 'Logo hover 位移')
    assert.equal(await css('.builders-team-card--coming-soon strong', 'color'), 'rgb(255, 255, 255)')
    await shot('.builders-strengths', '12-strengths')
    await shot('.builders-home-one', '13-home-one')
    assert.match(await css('.builders-service h3', 'fontFamily'), /Noto Serif TC/)
    assert.equal(await css('.builders-service p', 'color'), 'rgb(89, 88, 93)')
    assert.equal(await css('.builders-service p', 'marginTop'), '16px')
    assert.equal(await css('.builders-service p', 'gap'), '8px')
    await reveal('.builders-contact__tabs')
    await page.getByRole('tab', { name: '台中', exact: true }).click()
    assert.equal(await css('.builders-contact__tabs [aria-selected="true"]', 'color'), 'rgb(255, 255, 255)')
    await go('/builders/sakura-kitchen')
    assert.equal(await page.locator('.sakura-kitchen-hero.ev').count(), 0)
    assert.match(await page.locator('.sakura-kitchen-hero__image img').getAttribute('src'), /hero.webp$/)
    assert.equal(await page.locator('.sakura-kitchen-hero__project-card strong').textContent(), 'Brand Commitment')
    await shot('.sakura-kitchen-hero', '15-kitchen-hero')
    await shot('.sakura-kitchen-heading--series', '16-series')
    assert.equal(await css('#sakura-kitchen-series-title', 'fontSize'), '60px')
    await go('/builders/catalogues')
    assert.equal(await page.locator('h1').textContent(), 'Developer Catalogue')
    await reveal('.builder-catalogue-card__download')
    const downloaded = page.waitForEvent('download')
    await page.locator('.builder-catalogue-card__download').click()
    const download = await downloaded
    assert.equal(await download.failure(), null)
    assert.equal(fs.readFileSync(await download.path()).subarray(0, 5).toString(), '%PDF-')
    await shot('.builder-catalogue-card', '18-catalogue')
    for (const width of [768, 390]) {
      await page.setViewportSize({ width, height: 900 })
      for (const url of ['/about/advantage', '/about/introduce', '/franchising/intro', '/franchising/form', '/franchising/download', '/builders', '/builders/sakura-kitchen', '/builders/catalogues']) {
        await go(url)
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${url} ${width}px 溢出`)
      }
      await go('/builders')
      await shot('.builders-strengths', `${width}-strengths`)
      assert(await page.locator('.builders-strength__accent').evaluateAll(elements => elements.every(e => e.getBoundingClientRect().height <= parseFloat(getComputedStyle(e).lineHeight) * 2 + 1)), '能力卡片中間文字應維持兩行')
      await shot('.builders-home-one', `${width}-services`)
    }
    assert.deepEqual(errors, [], '前端執行錯誤')
    console.log('新版 18 頁 PPT：互動、排版、下載與響應式檢查通過')
  } finally { await browser.close() }
}
main().catch(e => { console.error(e); process.exitCode = 1 })
